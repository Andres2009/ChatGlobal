// Custom stickers stored in localStorage
const LS_KEY = 'realtime_chat_custom_stickers';

export function getCustomStickers() {
  try {
    return JSON.parse(localStorage.getItem(LS_KEY) ?? '[]');
  } catch {
    return [];
  }
}

export function addCustomSticker(url) {
  const stickers = getCustomStickers();
  const id = `custom_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`;
  stickers.unshift({ id, url, addedAt: new Date().toISOString() });
  localStorage.setItem(LS_KEY, JSON.stringify(stickers.slice(0, 60)));
  return id;
}

export function removeCustomSticker(id) {
  const stickers = getCustomStickers().filter((s) => s.id !== id);
  localStorage.setItem(LS_KEY, JSON.stringify(stickers));
}
